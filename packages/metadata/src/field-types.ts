import { z } from "zod";
import { MetadataError } from "./errors.js";

export const FIELD_TYPES = [
  "Text",
  "TextArea",
  "LongTextArea",
  "Email",
  "Phone",
  "Url",
  "Number",
  "Currency",
  "Percent",
  "Checkbox",
  "Date",
  "DateTime",
  "Picklist",
  "MultiselectPicklist",
  "Lookup",
  "MasterDetail",
  "AutoNumber",
] as const;

export type FieldType = (typeof FIELD_TYPES)[number];

const int = (min: number, max: number) => z.number().int().min(min).max(max);

const numeric = (defaultScale: number) =>
  z
    .object({
      // Total digits, as Salesforce's "length + decimal places" (max 18).
      precision: int(1, 18).default(18),
      scale: int(0, 17).default(defaultScale),
    })
    .strict()
    .refine((p) => p.scale < p.precision, {
      message: "Decimal places must be fewer than total digits.",
      path: ["scale"],
    });

/** {0000} for the number (1 to 10 digits); optional {YYYY} {YY} {MM} {DD}. */
export function checkAutoNumberFormat(format: string): void {
  if (format.length === 0 || format.length > 30) {
    throw new MetadataError(
      "INVALID_FIELD",
      "Display format must be 1 to 30 characters.",
      "displayFormat",
    );
  }
  const tokens = format.match(/\{[^}]*\}/g) ?? [];
  const numberTokens = tokens.filter((t) => /^\{0{1,10}\}$/.test(t));
  const bad = tokens.filter((t) => !/^\{0{1,10}\}$/.test(t) && !/^\{(YYYY|YY|MM|DD)\}$/.test(t));
  const stray = format.replace(/\{[^}]*\}/g, "").match(/[{}]/);
  if (numberTokens.length !== 1 || bad.length > 0 || stray) {
    throw new MetadataError(
      "INVALID_FIELD",
      'Display format needs exactly one number placeholder such as {0000}, and may use {YYYY}, {YY}, {MM} and {DD}. Example: "INV-{YYYY}-{0000}".',
      "displayFormat",
    );
  }
}

export type TypeSpec = {
  /** Type-specific settings and their defaults. Unknown keys are rejected. */
  props: z.ZodTypeAny;
  canBeRequired: boolean;
  canBeUnique: boolean;
  canBeExternalId: boolean;
  isRelationship: boolean;
  isPicklist: boolean;
};

const none = z.object({}).strict();

export const TYPE_SPECS: Record<FieldType, TypeSpec> = {
  Text: {
    props: z
      .object({ length: int(1, 255).default(255), caseSensitive: z.boolean().default(false) })
      .strict(),
    canBeRequired: true,
    canBeUnique: true,
    canBeExternalId: true,
    isRelationship: false,
    isPicklist: false,
  },
  TextArea: base(none, { required: true }),
  LongTextArea: base(
    z
      .object({ length: int(256, 131072).default(32768), visibleLines: int(2, 50).default(3) })
      .strict(),
    { required: true },
  ),
  Email: base(none, { required: true, unique: true, externalId: true }),
  Phone: base(none, { required: true }),
  Url: base(none, { required: true }),
  Number: base(numeric(0), { required: true, unique: true, externalId: true }),
  Currency: base(numeric(2), { required: true }),
  Percent: base(numeric(2), { required: true }),
  // A checkbox always has a value, so "required" doesn't apply.
  Checkbox: base(z.object({ defaultValue: z.boolean().default(false) }).strict(), {}),
  Date: base(none, { required: true }),
  DateTime: base(none, { required: true }),
  Picklist: {
    ...base(z.object({ restricted: z.boolean().default(true) }).strict(), { required: true }),
    isPicklist: true,
  },
  MultiselectPicklist: {
    ...base(
      z
        .object({ restricted: z.boolean().default(true), visibleLines: int(3, 10).default(4) })
        .strict(),
      { required: true },
    ),
    isPicklist: true,
  },
  Lookup: { ...base(none, { required: true }), isRelationship: true },
  // Always required; set by the platform, not the caller.
  MasterDetail: { ...base(none, {}), isRelationship: true },
  // Generated by the platform, so never required or editable.
  AutoNumber: base(
    z
      .object({
        displayFormat: z.string(),
        startingNumber: int(0, 999_999_999).default(1),
      })
      .strict(),
    { externalId: true },
  ),
};

function base(
  props: z.ZodTypeAny,
  can: { required?: boolean; unique?: boolean; externalId?: boolean },
): TypeSpec {
  return {
    props,
    canBeRequired: can.required ?? false,
    canBeUnique: can.unique ?? false,
    canBeExternalId: can.externalId ?? false,
    isRelationship: false,
    isPicklist: false,
  };
}

export function isFieldType(t: unknown): t is FieldType {
  return typeof t === "string" && (FIELD_TYPES as readonly string[]).includes(t);
}

/** Validates type-specific settings and fills in defaults. */
export function parseProps(
  type: FieldType,
  input: Record<string, unknown>,
): Record<string, unknown> {
  const result = TYPE_SPECS[type].props.safeParse(input);
  if (!result.success) {
    const issue = result.error.issues[0];
    const path = issue?.path.join(".") || undefined;
    const message =
      issue?.code === "unrecognized_keys"
        ? `${type} fields don't have ${issue.keys.map((k) => `"${k}"`).join(", ")}.`
        : `${path ?? "Field"}: ${issue?.message ?? "invalid"}`;
    throw new MetadataError(
      "INVALID_FIELD",
      message,
      issue?.code === "unrecognized_keys" ? issue.keys[0] : path,
    );
  }
  const props = result.data as Record<string, unknown>;
  if (type === "AutoNumber") checkAutoNumberFormat(String(props.displayFormat));
  return props;
}

export type PicklistValueInput = string | { value: string; label?: string; isDefault?: boolean };
export type PicklistValue = { value: string; label: string; isDefault: boolean };

/** Normalises and checks a list of picklist values. */
export function parsePicklistValues(
  type: FieldType,
  input: unknown,
  { min = 1, path = "values" }: { min?: number; path?: string } = {},
): PicklistValue[] {
  if (!Array.isArray(input)) {
    throw new MetadataError("INVALID_FIELD", "Picklist values must be a list.", path);
  }
  if (input.length < min || input.length > 1000) {
    throw new MetadataError("INVALID_FIELD", `A picklist needs ${min} to 1000 values.`, path);
  }
  const seen = new Set<string>();
  const values = input.map((raw, i): PicklistValue => {
    const v = typeof raw === "string" ? { value: raw } : (raw as Record<string, unknown>);
    const value = typeof v?.value === "string" ? v.value.trim() : "";
    const label = typeof v?.label === "string" && v.label.trim() ? v.label.trim() : value;
    if (!value || value.length > 255 || label.length > 255) {
      throw new MetadataError(
        "INVALID_FIELD",
        "Each picklist value must be 1 to 255 characters.",
        `${path}[${i}]`,
      );
    }
    if (type === "MultiselectPicklist" && value.includes(";")) {
      throw new MetadataError(
        "INVALID_FIELD",
        `Multi-select picklist values can't contain ";" (it separates selected values): "${value}".`,
        `${path}[${i}]`,
      );
    }
    const key = value.toLowerCase();
    if (seen.has(key)) {
      throw new MetadataError(
        "DUPLICATE_DEVELOPER_NAME",
        `Picklist value "${value}" appears more than once.`,
        `${path}[${i}]`,
      );
    }
    seen.add(key);
    return { value, label, isDefault: v?.isDefault === true };
  });
  if (values.filter((v) => v.isDefault).length > 1) {
    throw new MetadataError("INVALID_FIELD", "Only one picklist value can be the default.", path);
  }
  return values;
}
